// Variable study case
// Commonly used variable let, Const and var

// Variable -->>> used to store the code value 
// let -->> Value can be reassigned
// const -->> Value cannot be reassigned
// var -->> Value can be reassigned

// let variable code

let num_10=10
let num_20=20

// to show output in terminal
console.log(num_10)
console.log(num_20)

// now update the value using declaring another let
num_10= 100
num_20= 200
// to show latest change output in terminal
console.log(num_10)
console.log(num_20)

// const variable code

const name = "Parmeshwar";

//name = "Rahul";  // ❌ Error
console.log(name)

// var varible code -->> same as let variable code
